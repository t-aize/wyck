//! Turning bars into the lines of an indicator.

use super::config::StudyConfig;
use super::kind::StudyKind;
use super::spec::{DOWN, PlotKind, UP};
use wyck_core::math::{count_f64, count_i64, f64_to_i64, f64_to_usize};
use wyck_core::ta::{self, Series};

/// The kinds of moving average an indicator can offer, in the order of its `method` input.
pub(crate) const MA_METHODS: [&str; 5] = ["SMA", "EMA", "WMA", "RMA", "HMA"];

/// A moving average of `values`, by its position in [`MA_METHODS`].
pub(crate) fn moving_average(values: &[f64], length: usize, method: usize) -> Vec<f64> {
    match method {
        1 => ta::ema(values, length),
        2 => ta::wma(values, length),
        3 => ta::rma(values, length),
        4 => ta::hma(values, length),
        _ => ta::sma(values, length),
    }
}

/// The average at grouped bar `at` as it is while that bar is still forming: its source so far is
/// `now`, and the bars before it are final. `src` and `average` are the source and its average
/// over the finished grouped bars.
fn forming_average(
    src: &[f64],
    average: &[f64],
    at: usize,
    now: f64,
    length: usize,
    method: usize,
) -> f64 {
    let before = at.checked_sub(1);
    match method {
        // The exponential kinds only need the average one bar back.
        1 | 3 => {
            let alpha = if method == 1 {
                2.0 / (count_f64(length) + 1.0)
            } else {
                1.0 / count_f64(length)
            };
            match before.map(|b| average.at(b)) {
                Some(prev) if prev.is_finite() => alpha * now + (1.0 - alpha) * prev,
                _ => f64::NAN,
            }
        }
        // The others read a window: the bars before, then this one.
        _ => {
            let reach = length + f64_to_usize(count_f64(length).sqrt()) + 2;
            let start = at.saturating_sub(reach);
            let mut window: Vec<f64> = src.get(start..at).unwrap_or_default().to_vec();
            window.push(now);
            moving_average(&window, length, method)
                .last()
                .copied()
                .unwrap_or(f64::NAN)
        }
    }
}

/// The bars an indicator reads, as columns of numbers. Prices are raw (the server's integers as
/// real numbers), so an overlay shares the price scale of the chart.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct StudyInput {
    pub time: Vec<i64>,
    pub open: Vec<f64>,
    pub high: Vec<f64>,
    pub low: Vec<f64>,
    pub close: Vec<f64>,
    pub volume: Vec<f64>,
    /// Which day each bar is in (for anchoring VWAP), in the chart's time zone.
    pub day: Vec<i64>,
}

impl StudyInput {
    pub fn len(&self) -> usize {
        self.close.len()
    }

    pub fn is_empty(&self) -> bool {
        self.close.is_empty()
    }

    /// The price a source input names.
    pub fn source(&self, which: f64) -> Vec<f64> {
        let n = self.len();
        match f64_to_usize(which) {
            0 => self.open.clone(),
            1 => self.high.clone(),
            2 => self.low.clone(),
            4 => (0..n)
                .map(|i| f64::midpoint(self.high.at(i), self.low.at(i)))
                .collect(),
            5 => (0..n)
                .map(|i| (self.high.at(i) + self.low.at(i) + self.close.at(i)) / 3.0)
                .collect(),
            6 => (0..n)
                .map(|i| {
                    (self.open.at(i) + self.high.at(i) + self.low.at(i) + self.close.at(i)) / 4.0
                })
                .collect(),
            7 => (0..n)
                .map(|i| (self.high.at(i) + self.low.at(i) + 2.0 * self.close.at(i)) / 4.0)
                .collect(),
            _ => self.close.clone(),
        }
    }
}

/// One line (or histogram) of an indicator, a value per bar.
#[derive(Debug, Clone, PartialEq)]
pub struct PlotOut {
    pub key: &'static str,
    pub kind: PlotKind,
    pub values: Vec<f64>,
    /// How many bars later than its bar each value is drawn (negative: earlier). The leading
    /// spans of Ichimoku are drawn ahead of the prices.
    pub offset: i64,
    /// For a histogram: whether each column is up (colored `UP`) or down.
    pub up: Option<Vec<bool>>,
}

/// The shaded area between two plots.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FillOut {
    pub a: usize,
    pub b: usize,
    pub color: u32,
    pub alpha: f32,
    /// Colored by which plot is on top: `color` when `a` is above, this one otherwise.
    pub other: Option<u32>,
}

/// What an indicator draws.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct StudyOutput {
    pub plots: Vec<PlotOut>,
    pub fills: Vec<FillOut>,
    /// Drawings generated by this indicator. These never enter the user's drawing book.
    pub drawings: Vec<ScriptDrawing>,
    /// Horizontal lines: overbought and oversold, the zero line.
    pub levels: Vec<f64>,
    /// A shaded band between two levels.
    pub band: Option<(f64, f64)>,
}

/// A named drawing owned by one script instance.
#[derive(Debug, Clone, PartialEq)]
pub struct ScriptDrawing {
    pub key: String,
    pub drawing: wyck_drawings::model::Drawing,
}

/// The up and down colors of histograms and profiles.
pub const UP_COLOR: u32 = UP;
pub const DOWN_COLOR: u32 = DOWN;

pub(super) fn plot(key: &'static str, values: Vec<f64>) -> PlotOut {
    PlotOut {
        key,
        kind: PlotKind::Line,
        values,
        offset: 0,
        up: None,
    }
}

/// Computes an indicator over the bars. The volume profile is not computed here (it depends on
/// what is on screen, see [`super::profile`]); it gives an empty output.
pub fn compute(config: &StudyConfig, input: &StudyInput) -> StudyOutput {
    let n = input.len();
    let mut out = StudyOutput::default();
    if n == 0 {
        return out;
    }
    let source = || input.source(config.input("source"));
    let offset = f64_to_i64(config.input("offset"));
    match config.kind {
        StudyKind::Sma | StudyKind::Ema | StudyKind::Wma | StudyKind::Hma => {
            let length = config.length("length");
            let src = source();
            let values = match config.kind {
                StudyKind::Sma => ta::sma(&src, length),
                StudyKind::Ema => ta::ema(&src, length),
                StudyKind::Wma => ta::wma(&src, length),
                _ => ta::hma(&src, length),
            };
            out.plots.push(PlotOut {
                offset,
                ..plot("ma", values)
            });
        }
        StudyKind::MtfMa => {
            let length = config.length("length");
            let method = f64_to_usize(config.input("method"));
            let timeframe = wyck_market::Timeframe::from_code(&config.text("timeframe"));
            let values = match timeframe.and_then(|tf| super::higher::higher(input, tf)) {
                Some(grouped) => {
                    let which = config.input("source");
                    let src = grouped.input.source(which);
                    let average = moving_average(&src, length, method);
                    if config.input("confirmed") == 0.0 {
                        let live = grouped.forming.source(which);
                        (0..n)
                            .map(|i| {
                                let Some(&of) = grouped.of.get(i) else {
                                    return f64::NAN;
                                };
                                forming_average(&src, &average, of, live.at(i), length, method)
                            })
                            .collect()
                    } else {
                        super::higher::carry_back(&average, &grouped.of, true)
                    }
                }
                // No timeframe, or one that is not higher than the chart's: the chart's own bars.
                None => moving_average(&source(), length, method),
            };
            out.plots.push(PlotOut {
                offset,
                ..plot("ma", values)
            });
        }
        StudyKind::Vwap => {
            let src = source();
            let mut values = vec![f64::NAN; n];
            let mut deviation = vec![f64::NAN; n];
            let (mut pv, mut pv2, mut vol, mut anchor) = (0.0, 0.0, 0.0, None);
            for i in 0..n {
                let Some(&day) = input.day.get(i) else {
                    continue;
                };
                let period =
                    super::extended::pivot_period(day, f64_to_usize(config.input("anchor")));
                if anchor != Some(period) {
                    anchor = Some(period);
                    pv = 0.0;
                    pv2 = 0.0;
                    vol = 0.0;
                }
                if !src.at(i).is_finite() || !input.volume.at(i).is_finite() {
                    continue;
                }
                let v = input.volume.at(i).max(0.0);
                pv += src.at(i) * v;
                pv2 += src.at(i) * src.at(i) * v;
                vol += v;
                values.put(i, if vol > 0.0 { pv / vol } else { src.at(i) });
                let spread = if vol > 0.0 {
                    #[expect(
                        clippy::suspicious_operation_groupings,
                        reason = "the variance is E[x^2] minus the square of the mean"
                    )]
                    let variance = pv2 / vol - values.at(i) * values.at(i);
                    variance.max(0.0).sqrt()
                } else {
                    0.0
                };
                deviation.put(i, spread);
            }
            out.plots.push(plot("vwap", values));
            for (key, sign, mult) in [
                ("upper_1", 1.0, config.input("band_1")),
                ("lower_1", -1.0, config.input("band_1")),
                ("upper_2", 1.0, config.input("band_2")),
                ("lower_2", -1.0, config.input("band_2")),
            ] {
                let series = out.plots.first().map_or_else(Vec::new, |first| {
                    first
                        .values
                        .iter()
                        .zip(&deviation)
                        .map(|(v, d)| v + sign * mult * d)
                        .collect()
                });
                out.plots.push(plot(key, series));
            }
            out.fills.push(FillOut {
                a: 1,
                b: 2,
                color: config.plot_style("upper_1").color,
                alpha: 0.06,
                other: None,
            });
            out.fills.push(FillOut {
                a: 3,
                b: 4,
                color: config.plot_style("upper_2").color,
                alpha: 0.04,
                other: None,
            });
        }
        StudyKind::Bollinger => {
            let (length, mult) = (config.length("length"), config.input("mult"));
            let src = source();
            let basis =
                super::extended::average(&src, length, f64_to_usize(config.input("method")));
            let dev = ta::stdev(&src, length);
            let upper = basis.iter().zip(&dev).map(|(b, d)| b + mult * d).collect();
            let lower = basis.iter().zip(&dev).map(|(b, d)| b - mult * d).collect();
            out.plots.push(plot("basis", basis));
            out.plots.push(plot("upper", upper));
            out.plots.push(plot("lower", lower));
            out.fills.push(FillOut {
                a: 1,
                b: 2,
                color: config.plot_style("upper").color,
                alpha: 0.08,
                other: None,
            });
        }
        StudyKind::Keltner => {
            let (length, mult) = (config.length("length"), config.input("mult"));
            let basis =
                super::extended::average(&source(), length, f64_to_usize(config.input("method")));
            let range = ta::atr(&input.high, &input.low, &input.close, config.length("atr"));
            let upper = basis
                .iter()
                .zip(&range)
                .map(|(b, r)| b + mult * r)
                .collect();
            let lower = basis
                .iter()
                .zip(&range)
                .map(|(b, r)| b - mult * r)
                .collect();
            out.plots.push(plot("basis", basis));
            out.plots.push(plot("upper", upper));
            out.plots.push(plot("lower", lower));
            out.fills.push(FillOut {
                a: 1,
                b: 2,
                color: config.plot_style("upper").color,
                alpha: 0.06,
                other: None,
            });
        }
        StudyKind::Donchian => {
            let length = config.length("length");
            let upper = ta::highest(&input.high, length);
            let lower = ta::lowest(&input.low, length);
            let basis = upper
                .iter()
                .zip(&lower)
                .map(|(u, l)| (u + l) / 2.0)
                .collect();
            out.plots.push(plot("basis", basis));
            out.plots.push(plot("upper", upper));
            out.plots.push(plot("lower", lower));
            out.fills.push(FillOut {
                a: 1,
                b: 2,
                color: config.plot_style("upper").color,
                alpha: 0.06,
                other: None,
            });
        }
        StudyKind::Ichimoku => {
            let middle = |length: usize| -> Vec<f64> {
                let (h, l) = (
                    ta::highest(&input.high, length),
                    ta::lowest(&input.low, length),
                );
                h.iter().zip(&l).map(|(h, l)| (h + l) / 2.0).collect()
            };
            let conversion = middle(config.length("conversion"));
            let base = middle(config.length("base"));
            let span_a: Vec<f64> = conversion
                .iter()
                .zip(&base)
                .map(|(c, b)| (c + b) / 2.0)
                .collect();
            let span_b = middle(config.length("span_b"));
            let shift = count_i64(config.length("displacement")) - 1;
            out.plots.push(plot("conversion", conversion));
            out.plots.push(plot("base", base));
            out.plots.push(PlotOut {
                offset: -shift,
                ..plot("lagging", input.close.clone())
            });
            out.plots.push(PlotOut {
                offset: shift,
                ..plot("span_a", span_a)
            });
            out.plots.push(PlotOut {
                offset: shift,
                ..plot("span_b", span_b)
            });
            out.fills.push(FillOut {
                a: 3,
                b: 4,
                color: 0x43_a047,
                alpha: 0.12,
                other: Some(0xf4_4336),
            });
        }
        StudyKind::ParabolicSar => {
            let values = ta::parabolic_sar(
                &input.high,
                &input.low,
                config.input("start"),
                config.input("step"),
                config.input("max"),
            );
            out.plots.push(PlotOut {
                kind: PlotKind::Dots,
                ..plot("sar", values)
            });
        }
        StudyKind::VolumeProfile | StudyKind::Unknown | StudyKind::Custom => {}
        StudyKind::Volume => {
            let up = (0..n)
                .map(|i| input.close.at(i) >= input.open.at(i))
                .collect();
            out.plots.push(PlotOut {
                kind: PlotKind::Histogram,
                up: Some(up),
                ..plot("volume", input.volume.clone())
            });
            out.plots
                .push(plot("ma", ta::sma(&input.volume, config.length("ma"))));
        }
        StudyKind::Rsi => {
            out.plots
                .push(plot("rsi", ta::rsi(&source(), config.length("length"))));
            let (upper, lower) = (config.input("upper"), config.input("lower"));
            out.levels = vec![upper, 50.0, lower];
            out.band = Some((lower, upper));
        }
        StudyKind::Macd => {
            let (line, signal, hist) = ta::macd(
                &source(),
                config.length("fast"),
                config.length("slow"),
                config.length("signal"),
            );
            let up = hist.iter().map(|h| *h >= 0.0).collect();
            out.plots.push(PlotOut {
                kind: PlotKind::Histogram,
                up: Some(up),
                ..plot("histogram", hist)
            });
            out.plots.push(plot("macd", line));
            out.plots.push(plot("signal", signal));
            out.levels = vec![0.0];
        }
        StudyKind::Stochastic => {
            let (k, d) = ta::stochastic(
                &input.high,
                &input.low,
                &input.close,
                config.length("length"),
                config.length("smooth"),
                config.length("d"),
            );
            out.plots.push(plot("k", k));
            out.plots.push(plot("d", d));
            let (upper, lower) = (config.input("upper"), config.input("lower"));
            out.levels = vec![upper, lower];
            out.band = Some((lower, upper));
        }
        StudyKind::Atr => {
            let tr = ta::true_range(&input.high, &input.low, &input.close);
            let smooth = |values: &[f64], length: usize, method: usize| match method {
                1 => ta::sma(values, length),
                2 => ta::ema(values, length),
                3 => ta::wma(values, length),
                _ => ta::rma(values, length),
            };
            let mut atr = smooth(
                &tr,
                config.length("length"),
                f64_to_usize(config.input("smoothing")),
            );
            let mut tr = tr;
            if config.input("unit").total_cmp(&1.0).is_eq() {
                for (close, (atr_value, tr_value)) in
                    input.close.iter().zip(atr.iter_mut().zip(tr.iter_mut()))
                {
                    let scale = if close.is_finite() && *close != 0.0 {
                        100.0 / close.abs()
                    } else {
                        f64::NAN
                    };
                    *atr_value *= scale;
                    *tr_value *= scale;
                }
            }
            let signal = smooth(
                &atr,
                config.length("signal_length"),
                f64_to_usize(config.input("signal_smoothing")),
            );
            out.plots.push(plot("atr", atr));
            out.plots.push(plot("signal", signal));
            out.plots.push(plot("tr", tr));
        }
        StudyKind::Cci => {
            let typical = input.source(5.0);
            out.plots
                .push(plot("cci", ta::cci(&typical, config.length("length"))));
            let (upper, lower) = (config.input("upper"), config.input("lower"));
            out.levels = vec![upper, 0.0, lower];
            out.band = Some((lower.min(upper), upper.max(lower)));
        }
        StudyKind::WilliamsR => {
            out.plots.push(plot(
                "r",
                ta::williams_r(
                    &input.high,
                    &input.low,
                    &input.close,
                    config.length("length"),
                ),
            ));
            let (upper, lower) = (config.input("upper"), config.input("lower"));
            out.levels = vec![upper, lower];
            out.band = Some((lower.min(upper), upper.max(lower)));
        }
        StudyKind::Momentum => {
            out.plots.push(plot(
                "mom",
                ta::momentum(&source(), config.length("length")),
            ));
            out.levels = vec![0.0];
        }
        StudyKind::Obv => {
            out.plots
                .push(plot("obv", ta::obv(&input.close, &input.volume)));
        }
        StudyKind::Dmi => {
            let (plus, minus, adx) = ta::dmi(
                &input.high,
                &input.low,
                &input.close,
                config.length("length"),
                config.length("smoothing"),
            );
            out.plots.push(plot("adx", adx));
            out.plots.push(plot("plus", plus));
            out.plots.push(plot("minus", minus));
            out.levels = vec![25.0];
        }
        other => return super::extended::compute(other, config, input),
    }
    out
}
