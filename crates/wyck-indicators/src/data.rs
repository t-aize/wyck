//! What an indicator reads and what it gives back: the bars as columns of numbers
//! ([`StudyInput`]) and the lines, fills and drawings it makes ([`StudyOutput`]).

use super::spec::{DOWN, PlotKind, UP};
use wyck_core::math::f64_to_usize;
use wyck_core::ta::Series as _;

/// The bars an indicator reads, as columns of numbers. Prices are raw (the server's integers as
/// real numbers), so an overlay shares the price scale of the chart.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct StudyInput {
    pub time: Vec<i64>,
    pub open: Vec<f64>,
    pub high: Vec<f64>,
    pub low: Vec<f64>,
    pub close: Vec<f64>,
    pub volume: Vec<f64>,
    /// Which day each bar is in (for anchoring VWAP), in the chart's time zone.
    pub day: Vec<i64>,
}

impl StudyInput {
    pub fn len(&self) -> usize {
        self.close.len()
    }

    pub fn is_empty(&self) -> bool {
        self.close.is_empty()
    }

    /// The price a source input names.
    pub fn source(&self, which: f64) -> Vec<f64> {
        let n = self.len();
        match f64_to_usize(which) {
            0 => self.open.clone(),
            1 => self.high.clone(),
            2 => self.low.clone(),
            4 => (0..n)
                .map(|i| f64::midpoint(self.high.at(i), self.low.at(i)))
                .collect(),
            5 => (0..n)
                .map(|i| (self.high.at(i) + self.low.at(i) + self.close.at(i)) / 3.0)
                .collect(),
            6 => (0..n)
                .map(|i| {
                    (self.open.at(i) + self.high.at(i) + self.low.at(i) + self.close.at(i)) / 4.0
                })
                .collect(),
            7 => (0..n)
                .map(|i| (self.high.at(i) + self.low.at(i) + 2.0 * self.close.at(i)) / 4.0)
                .collect(),
            _ => self.close.clone(),
        }
    }
}

/// One line (or histogram) of an indicator, a value per bar.
#[derive(Debug, Clone, PartialEq)]
pub struct PlotOut {
    pub key: &'static str,
    pub kind: PlotKind,
    pub values: Vec<f64>,
    /// How many bars later than its bar each value is drawn (negative: earlier). The leading
    /// spans of Ichimoku are drawn ahead of the prices.
    pub offset: i64,
    /// For a histogram: whether each column is up (colored `UP`) or down.
    pub up: Option<Vec<bool>>,
}

/// The shaded area between two plots.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FillOut {
    pub a: usize,
    pub b: usize,
    pub color: u32,
    pub alpha: f32,
    /// Colored by which plot is on top: `color` when `a` is above, this one otherwise.
    pub other: Option<u32>,
}

/// What an indicator draws.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct StudyOutput {
    pub plots: Vec<PlotOut>,
    pub fills: Vec<FillOut>,
    /// Drawings generated by this indicator. These never enter the user's drawing book.
    pub drawings: Vec<ScriptDrawing>,
    /// Horizontal lines: overbought and oversold, the zero line.
    pub levels: Vec<f64>,
    /// A shaded band between two levels.
    pub band: Option<(f64, f64)>,
}

/// A named drawing owned by one script instance.
#[derive(Debug, Clone, PartialEq)]
pub struct ScriptDrawing {
    pub key: String,
    pub drawing: wyck_drawings::model::Drawing,
}

/// The up and down colors of histograms and profiles.
pub const UP_COLOR: u32 = UP;
pub const DOWN_COLOR: u32 = DOWN;

pub(crate) fn plot(key: &'static str, values: Vec<f64>) -> PlotOut {
    PlotOut {
        key,
        kind: PlotKind::Line,
        values,
        offset: 0,
        up: None,
    }
}
